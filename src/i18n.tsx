type I18nContextValue = {
  language: Language;
  languagePreference: LanguagePreference;
  locale: string;
  setLanguage(language: LanguagePreference): void;
  t(key: string, values?: TranslationValues): string;
  formatError(cause: unknown): string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function systemLanguage(): Language {
  if (typeof window === "undefined") return "en";
  return window.navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

function detectLanguagePreference(): LanguagePreference {
  if (typeof window === "undefined") return "system";
  const stored = window.localStorage.getItem("byfinity.language");
  return stored === "en" || stored === "fr" || stored === "system" ? stored : "system";
}

function interpolate(value: string, variables: TranslationValues = {}) {
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? `{${key}}`));
}

function errorText(cause: unknown) {
  const value = cause instanceof Error ? cause.message : String(cause);
  return value.replace(/^Error:\s*/i, "").trim();
}

function translateError(message: string, translate: (key: string, values?: TranslationValues) => string) {
  const exact = translate(message);
  if (exact !== message) return exact;

  const patterns: Array<[RegExp, string]> = [
    [/^Hermes profile ['’](.+)['’] not found$/, "Hermes profile “{name}” was not found"],
    [/^Profile ['’](.+)['’] already exists$/, "Profile “{name}” already exists"],
    [/^Group ['’](.+)['’] already exists$/, "Group “{name}” already exists"],
    [/^Unknown group ['’](.+)['’]$/, "Unknown group “{name}”"],
    [/^The (admin|operator|viewer) role cannot perform this action\.$/, "The {role} role cannot perform this action."],
    [/^Hermes health check failed \((\d+)\)$/, "Hermes health check failed ({status})"]
  ];
  for (const [pattern, key] of patterns) {
    const match = message.match(pattern);
    if (match) return translate(key, key.includes("{role}") ? { role: match[1] } : key.includes("{status}") ? { status: match[1] } : { name: match[1] });
  }
  return message;
}

export function LanguageProvider({ children, initialLanguage }: { children: ReactNode; initialLanguage?: Language }) {
  const [languagePreference, setLanguage] = useState<LanguagePreference>(() => initialLanguage ?? detectLanguagePreference());
  const [detectedLanguage, setDetectedLanguage] = useState<Language>(() => systemLanguage());
  const language = languagePreference === "system" ? detectedLanguage : languagePreference;

  useEffect(() => {
    if (languagePreference !== "system") return;
    const updateLanguage = () => setDetectedLanguage(systemLanguage());
    window.addEventListener("languagechange", updateLanguage);
    return () => window.removeEventListener("languagechange", updateLanguage);
  }, [languagePreference]);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem("byfinity.language", languagePreference);
  }, [language, languagePreference]);

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: string, variables?: TranslationValues) => {
      const message = language === "fr" ? french[key] ?? key : key;
      return interpolate(message, variables);
    };
    return {
      language,
      languagePreference,
      locale: language === "fr" ? "fr-FR" : "en-US",
      setLanguage,
      t,
      formatError(cause) {
        return translateError(errorText(cause), t);
      }
    };
  }, [language, languagePreference]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}
